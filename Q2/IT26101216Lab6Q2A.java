public class IT26101216Lab6Q2A {
    public static void main(String[] args) {
        
        int i = 1;
        
        // Use a while loop to print numbers from 1 to 10
        while (i <= 10) {
            System.out.print(i + " ");
            i++;
        }
        
        // Move to the next line after printing all numbers
        System.out.println();
    }
}